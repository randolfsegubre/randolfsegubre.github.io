using System.Text.Json.Serialization;

namespace Portfolio.Business.Models;

/// <summary>
/// Facts about the deployed site itself (not about the owner), kept in one place so the page head, the sitemap
/// and the tests can never disagree about the address.
/// </summary>
/// <param name="Url">The public address of the site, with no trailing slash. It is where GitHub Pages serves the site (ADR-0001).</param>
/// <param name="Description">The search-result description of the home page. Prose, so it follows the writing rules.</param>
/// <param name="ShareDescription">The description link previews show. Prose, so it follows the writing rules.</param>
/// <param name="HeroLogoCount">How many of the profile's backdrop technologies float inside the hero (the first ones in the list); all the others go in the page layer. The hero keeps only a few, in its top padding, because the hero's height changes at every screen size and that padding is the one place content never occupies.</param>
public sealed record SiteSettings(string Url, string Description, string ShareDescription, int HeroLogoCount);

/// <summary>
/// The skills map as it is written down, before it is laid out in space: the tree, the extra lines and the walk order.
/// </summary>
/// <remarks>
/// This is the shape of <c>content/skill-universe.json</c>. The positions are not stored: they are worked out from this
/// by <c>SkillUniverseLayout</c> when the content is loaded, so the data holds only what the owner decided.
/// </remarks>
/// <param name="Intro">A short line above the map. Prose, so it follows the writing rules.</param>
/// <param name="Stars">The tree: exactly one star with no parent, every other star pointing at its parent.</param>
/// <param name="CrossLinks">Extra lines between stars that are related but not parent and child.</param>
/// <param name="Journey">The order the "walk my journey" button visits the stars; each star appears exactly once.</param>
public sealed record UniverseSource(
    string Intro,
    IReadOnlyList<SkillStar> Stars,
    IReadOnlyList<SkillLink> CrossLinks,
    IReadOnlyList<string> Journey);

/// <summary>
/// One lane of scrolling code in the page background: decoration that makes the page look like it is showing its own source.
/// </summary>
/// <param name="Code">The code text. It makes no claim about the owner beyond what the page already says.</param>
/// <param name="Seconds">How long one loop takes.</param>
/// <param name="Reverse">True when the lane scrolls the other way.</param>
public sealed record CodeStream(string Code, int Seconds, bool Reverse);

/// <summary>
/// One technology logo drawn as inline vector markup (ADR-0008).
/// </summary>
/// <param name="Key">The technology name exactly as it appears in a project or role stack, so a test can prove the page backs it up.</param>
/// <param name="Hex">The brand color the logo is filled with.</param>
/// <param name="Markup">The shapes inside a 24 by 24 view box. Trusted, static markup written or generated by the site's author, never user input.</param>
public sealed record TechLogo(string Key, string Hex, string Markup)
{
    /// <summary>
    /// The id of this logo's shared <c>&lt;symbol&gt;</c> in the page's hidden sprite, for example "logo-csharp".
    /// </summary>
    /// <remarks>
    /// Each logo is drawn once in the sprite and every place that shows it references it with <c>&lt;use&gt;</c>, which
    /// keeps the page small however many times a logo repeats. Characters that are not valid in an id are spelled out:
    /// "#" becomes "sharp" and "." becomes "dot", so "C#" is "logo-csharp" and ".NET 10" is "logo-dotnet-10".
    /// </remarks>
    [JsonIgnore]
    public string SymbolId => "logo-" + Key.ToLowerInvariant().Replace("#", "sharp", StringComparison.Ordinal).Replace(".", "dot", StringComparison.Ordinal).Replace(" ", "-", StringComparison.Ordinal);
}

/// <summary>
/// An icon shown inside a skills-map sphere, drawn as inline vector markup (ADR-0010).
/// </summary>
/// <param name="Key">The name stars use to refer to it, for example "database" or "javascript".</param>
/// <param name="Markup">The shapes inside a 24 by 24 view box. Trusted, static markup written by the site's author, never user input.</param>
/// <param name="Fill">The brand colour a logo is filled with, or null for a plain line glyph that takes the text colour.</param>
/// <param name="OnDark">True when the mark needs a dark sphere to stay readable (for example the yellow JavaScript logo).</param>
public sealed record SkillIcon(string Key, string Markup, string? Fill = null, bool OnDark = false)
{
    /// <summary>The id of this icon's shared <c>&lt;symbol&gt;</c> in the skills sprite, for example "skillicon-database".</summary>
    [JsonIgnore]
    public string SymbolId => "skillicon-" + Key;
}

/// <summary>
/// Where a star's icon comes from once its key is looked up: which sprite symbol to draw and how.
/// </summary>
/// <param name="SymbolId">The id of the symbol to reference with <c>&lt;use&gt;</c>.</param>
/// <param name="Fill">The brand colour, or null for a line glyph.</param>
/// <param name="OnDark">True when the sphere should be the dark variant.</param>
public sealed record ResolvedIcon(string SymbolId, string? Fill, bool OnDark);

/// <summary>
/// The small icon shown beside a profile link (GitHub, LinkedIn), found by the link's label.
/// </summary>
/// <remarks>
/// Exactly one of <paramref name="LogoKey"/> and <paramref name="Markup"/> is set. Both icons are drawn in the current
/// text color, so they follow the button's color and hover state. Decorative: the link text still names the destination.
/// </remarks>
/// <param name="Label">The profile link's label, compared without regard to case and surrounding spaces.</param>
/// <param name="LogoKey">The key of a technology logo to reuse (GitHub uses the one already drawn for the backdrop), or null.</param>
/// <param name="Markup">The shapes inside a 24 by 24 view box, drawn for this site, or null when a technology logo is reused.</param>
public sealed record SocialIcon(string Label, string? LogoKey = null, string? Markup = null);
